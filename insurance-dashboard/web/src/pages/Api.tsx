/** the first record of a file, as build_api_doc.py prints it: header scalars and the first item of the first list of records */
function firstRecord(d: unknown): unknown {
  const trim = (x: unknown, depth: number): unknown => {
    if (Array.isArray(x)) return x.length ? [trim(x[0], depth + 1)] : [];
    if (x && typeof x === 'object' && depth < 3) return Object.fromEntries(Object.entries(x as Record<string, unknown>).slice(0, 8).map(([k, v]) => [k, trim(v, depth + 1)]));
    return x;
  };
  if (d && typeof d === 'object' && !Array.isArray(d)) {
    const e = Object.entries(d as Record<string, unknown>);
    const recs = e.find(([, v]) => Array.isArray(v) && v.length > 0 && typeof v[0] === 'object');
    if (recs) d = { ...Object.fromEntries(e.filter(([, v]) => v === null || typeof v !== 'object').slice(0, 4)), [recs[0]]: [(recs[1] as unknown[])[0]] };
  }
  return trim(d, 0);
}

function Example({ path }: { path: string }) {
  const [st, setSt] = useState<{ text?: string; err?: string } | null>(null);
  if (!path.endsWith('.json')) return <a className="mono" dir="ltr" href={`/data/${path}`} download>{path}</a>;
  const load = async () => {
    setSt({});
    try { const r = await fetch(`/data/${path}`); if (!r.ok) throw new Error(String(r.status)); const s = JSON.stringify(firstRecord(await r.json()), null, 1); setSt({ text: s.length > 1600 ? `${s.slice(0, 1600)}…` : s }); }
    catch (e) { setSt({ err: String(e) }); }
  };
  return (
    <div className="api-ex">
      <a className="mono" dir="ltr" href={`/data/${path}`} target="_blank" rel="noreferrer">{path}</a>
      {!st ? <button type="button" className="chip" onClick={() => void load()}>רשומה ראשונה</button>
        : st.err ? <span className="neg">לא נטען ({st.err})</span> : st.text ? <pre dir="ltr">{st.text}</pre> : <span className="muted">טוען…</span>}
    </div>
  );
}

