export interface MSrc { t: string; url: string; kind: 'primary' | 'reference' | 'issuer'; pg?: number; read: string }
/** the link's words in a rule line: short, the publisher and the page */
export function shortOf(s: MSrc): string {
  if (s.kind === 'reference') return 'כל זכות';
  if (s.kind === 'issuer') return s.t.split(':')[0];
  const circ = /^חוזר גופים מוסדיים (\d{4}-\d+-\d+)/.exec(s.t);
  const who = circ ? `חוזר ${circ[1]}` : s.t.startsWith('תקנות') ? 'התקנות' : s.t.split(/[:[]/)[0].trim();
  return `${who}${s.pg ? `, עמ' ${s.pg}` : ''}`;
}
